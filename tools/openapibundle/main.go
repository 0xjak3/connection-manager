// Command openapibundle bundles the split spec under api/ into a single file
// with no external refs (api/openapi.gen.yaml). Components are named exactly
// as the root's components.schemas keys, and every schema ref becomes
// #/components/schemas/<Name>. See .claude/rules/openapi.md.
//
// Usage (from the project root): go run ./tools/openapibundle [-in api/openapi.yaml] [-out api/openapi.gen.yaml]
package main

import (
	"bytes"
	"context"
	"errors"
	"flag"
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/getkin/kin-openapi/openapi3"
	"go.yaml.in/yaml/v3"
)

const header = "# GENERATED by tools/openapibundle from api/openapi.yaml. DO NOT EDIT.\n# Edit api/openapi.yaml, api/paths/*.yaml or api/schemas/*.yaml and run 'make generate'.\n"

func main() {
	in := flag.String("in", "api/openapi.yaml", "root spec")
	out := flag.String("out", "api/openapi.gen.yaml", "bundled output")
	flag.Parse()

	b, err := bundle(*in)
	if err != nil {
		fmt.Fprintln(os.Stderr, "openapibundle:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, b, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "openapibundle:", err)
		os.Exit(1)
	}
}

// bundle loads the root spec with its external refs and returns the bundled,
// validated document as YAML.
func bundle(rootPath string) ([]byte, error) {
	ctx := context.Background()
	rootDir, err := filepath.Abs(filepath.Dir(rootPath))
	if err != nil {
		return nil, err
	}
	doc, err := load(ctx, rootPath)
	if err != nil {
		return nil, err
	}
	names, err := rootSchemaNames(doc, rootDir)
	if err != nil {
		return nil, err
	}
	if err := internalize(ctx, doc, names, rootDir); err != nil {
		return nil, err
	}
	if err := checkSchemaFiles(rootDir, names); err != nil {
		return nil, err
	}

	// Round-trip through the marshalled form: this proves the output needs no
	// external files, and validates exactly what is written.
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return nil, fmt.Errorf("marshal: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("marshal: %w", err)
	}
	body := buf.Bytes()
	check, err := openapi3.NewLoader().LoadFromData(body)
	if err != nil {
		return nil, fmt.Errorf("reload bundle: %w", err)
	}
	if err := check.Validate(ctx); err != nil {
		return nil, fmt.Errorf("validate bundle: %w", err)
	}
	return append([]byte(header), body...), nil
}

func load(ctx context.Context, rootPath string) (*openapi3.T, error) {
	loader := openapi3.NewLoader()
	loader.IsExternalRefsAllowed = true
	loader.Context = ctx
	doc, err := loader.LoadFromFile(rootPath)
	if err != nil {
		return nil, fmt.Errorf("load %s: %w", rootPath, err)
	}
	if err := doc.Validate(ctx); err != nil {
		return nil, fmt.Errorf("validate %s: %w", rootPath, err)
	}
	return doc, nil
}

// target is the absolute "<file>#<pointer>" a resolved ref points at, so refs
// written relative to different files compare equal.
func target(u *url.URL) string {
	p, err := filepath.Abs(filepath.FromSlash(u.Path))
	if err != nil {
		p = u.Path
	}
	return p + "#" + u.Fragment
}

// display shortens a target to "<file relative to the root dir>#<pointer>".
func display(t, rootDir string) string {
	if rel, ok := strings.CutPrefix(t, rootDir+string(filepath.Separator)); ok {
		return filepath.ToSlash(rel)
	}
	return t
}

// rootSchemaNames maps every root components.schemas target to its key. Every
// entry must be a $ref, and no two keys may point at the same schema.
func rootSchemaNames(doc *openapi3.T, rootDir string) (map[string]string, error) {
	if doc.Components == nil || len(doc.Components.Schemas) == 0 {
		return nil, errors.New("root has no components.schemas")
	}
	keys := make([]string, 0, len(doc.Components.Schemas))
	for name := range doc.Components.Schemas {
		keys = append(keys, name)
	}
	sort.Strings(keys)

	names := map[string]string{} // target → component name
	for _, name := range keys {
		s := doc.Components.Schemas[name]
		if s.Ref == "" || s.RefPath() == nil {
			return nil, fmt.Errorf("components.schemas.%s must be a $ref to a schema file, not an inline schema", name)
		}
		t := target(s.RefPath())
		if other, dup := names[t]; dup {
			return nil, fmt.Errorf("components.schemas.%s and components.schemas.%s point at the same schema %s",
				other, name, display(t, rootDir))
		}
		names[t] = name
	}
	return names, nil
}

// internalize rewrites every ref to a local #/components/schemas/<Name>, where
// Name is the root components.schemas key that points at the same target.
// A ref to anything not listed there (or to a non-schema) is an error.
func internalize(ctx context.Context, doc *openapi3.T, names map[string]string, rootDir string) error {
	unknown := map[string]bool{}
	doc.InternalizeRefs(ctx, func(_ *openapi3.T, ref openapi3.ComponentRef) string {
		var t string
		if ref.RefPath() != nil {
			t = target(ref.RefPath())
		}
		if _, isSchema := ref.(*openapi3.SchemaRef); isSchema && t != "" {
			if name, ok := names[t]; ok {
				return name
			}
		}
		label := ref.RefString()
		if t != "" {
			label = display(t, rootDir)
		}
		unknown[fmt.Sprintf("%s %s", ref.CollectionName(), label)] = true
		return "Unknown"
	})
	if len(unknown) > 0 {
		return fmt.Errorf("refs not listed in root components.schemas (only schema refs are supported): %s",
			strings.Join(sortedKeys(unknown), ", "))
	}
	return nil
}

// checkSchemaFiles fails when a top-level key of any <rootDir>/schemas/*.yaml
// has no root components.schemas entry: it would otherwise be dropped from the
// bundle without notice.
func checkSchemaFiles(rootDir string, names map[string]string) error {
	files, err := filepath.Glob(filepath.Join(rootDir, "schemas", "*.yaml"))
	if err != nil {
		return err
	}
	unlisted := map[string]bool{}
	for _, f := range files {
		raw, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		var top map[string]any
		if err := yaml.Unmarshal(raw, &top); err != nil {
			return fmt.Errorf("parse %s: %w", display(f, rootDir), err)
		}
		for key := range top {
			t := f + "#/" + key
			if _, ok := names[t]; !ok {
				unlisted[display(t, rootDir)] = true
			}
		}
	}
	if len(unlisted) > 0 {
		return fmt.Errorf("schemas with no root components.schemas entry: %s",
			strings.Join(sortedKeys(unlisted), ", "))
	}
	return nil
}

func sortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
